import assert from "node:assert/strict";
import { copyFileSync, existsSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const dir = process.env.TMPDIR;
const modulePath = join(dir, "workbench-opencode-tracker.mjs");
copyFileSync(process.argv[2], modulePath);
const tracker = (await import(pathToFileURL(modulePath))).default;
const state = join(dir, "opencode-tracking");
process.env.TMUX_ASSISTANT_RESURRECT_DIR = state;
process.env.TMUX_PANE = "%42";
process.env.WB_PRIVATE_TEST = "must-not-be-saved";
let route = { type: "home" };
const context = { ui: { router: { current: () => route }, model: { current: () => ({ providerID: "test", modelID: "model" }) } } };
const file = join(state, `opencode-${process.pid}.json`);
const pause = () => new Promise((resolve) => setTimeout(resolve, 400));
const stop = tracker.setup(context);
assert.equal(existsSync(file), false);
route = { type: "session", sessionID: "ses_first" };
await pause();
let data = JSON.parse(readFileSync(file, "utf8"));
assert.equal(data.session_id, "ses_first");
assert.equal(data.env.tmux_pane, "%42");
assert.equal(data.model, "test/model");
assert.equal(data.env.WB_PRIVATE_TEST, undefined);
assert.equal(statSync(file).mode & 0o777, 0o600);
route = { type: "session", sessionID: "ses_switched" };
await pause();
data = JSON.parse(readFileSync(file, "utf8"));
assert.equal(data.session_id, "ses_switched");
route = { type: "home" };
await pause();
assert.equal(existsSync(file), false);
route = { type: "session", sessionID: "ses_final" };
await pause();
writeFileSync(file, JSON.stringify({ workbench_instance: "another-instance" }));
stop();
assert.equal(JSON.parse(readFileSync(file, "utf8")).workbench_instance, "another-instance");
console.log("OpenCode 2 foreground tracker: ok");
